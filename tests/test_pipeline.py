class _TextAdapter:
    def __init__(self, text):
        self.text = text

    def call_text_only(self, system, user, max_tokens):
        return LLMResponse(text=self.text, sources=[])


class TestDisambiguate:
    def test_guard_sentence_is_invalid(self):
        """Haiku 5.5 replies with the injection guard's plain sentence, not JSON."""
        adapter = _TextAdapter("This does not appear to be a valid company name.")
        assert app._disambiguate(adapter, "asdf qwerty")["status"] == "invalid"

    def test_json_is_parsed(self):
        adapter = _TextAdapter('```json\n{"status": "clear", "company": "Notion"}\n```')
        assert app._disambiguate(adapter, "notion") == {"status": "clear", "company": "Notion"}

    def test_unparseable_output_defaults_to_clear(self):
        adapter = _TextAdapter("")
        assert app._disambiguate(adapter, "Acme") == {"status": "clear", "company": "Acme"}
