ANTHROPIC = PROVIDER_CONFIGS["anthropic"]
OPENAI = PROVIDER_CONFIGS["openai"]
_SYSTEM_TO_KEY = {spec.system: spec.key for spec in PASSES}

FAKE_SYNTHESIS = (
    "**Key facts**\n- Founded: 2000\n\n"
    "**What they do** — Things.\n\n"
    "**What they're doing** — Stuff.\n\n"
    "**Bottom line** — Fine.\n\n"
    "*Generated by Company Intelligence Agent — an agentic AI research tool by Hollis Cooper*"
)


class FakeFactory:
    """Stands in for providers.make_adapter."""

    def __init__(self, errors=None, delays=None):
        self.errors = errors or {}    # (provider, key) -> exception instance
        self.delays = delays or {}    # key -> seconds
        self.calls: list[tuple[str, str, str]] = []  # (provider, model, key)
        self.synthesis_prompts: list[str] = []
        self._lock = threading.Lock()

    def __call__(self, provider, api_key, model, timeout=90.0, max_retries=2):
        return FakeAdapter(self, provider, model)

    def record(self, provider, model, key):
        with self._lock:
            self.calls.append((provider, model, key))

    def model_for(self, key):
        return {k: m for _, m, k in self.calls}.get(key)


class FakeAdapter:
    def __init__(self, factory, provider, model):
        self.f, self.provider, self.model = factory, provider, model

    def call_with_search(self, system, user, max_tokens, max_search_uses):
        key = _SYSTEM_TO_KEY[system]
        self.f.record(self.provider, self.model, key)
        time.sleep(self.f.delays.get(key, 0))
        if (self.provider, key) in self.f.errors:
            raise self.f.errors[(self.provider, key)]
        return LLMResponse(
            text=f"{key} research via {self.provider}",
            sources=[{"url": f"https://example.com/{key}", "title": key}],
        )

    def call_text_only(self, system, user, max_tokens):
        self.f.record(self.provider, self.model, "synthesis")
        if (self.provider, "synthesis") in self.f.errors:
            raise self.f.errors[(self.provider, "synthesis")]
        self.f.synthesis_prompts.append(user)
        return LLMResponse(text=FAKE_SYNTHESIS, sources=[])


@pytest.fixture
def fake(monkeypatch):
    factory = FakeFactory()
    monkeypatch.setattr(app, "make_adapter", factory)
    monkeypatch.setattr(app, "save_cache", lambda company, brief: None)
    return factory


def _run(fallback=None, messages=None):
    sink = messages if messages is not None else []
    return run_pipeline("Acme", "key", "anthropic", sink.append, fallback=fallback)


class TestParallelPipeline:
    def test_passes_run_concurrently(self, fake):
        fake.delays = {spec.key: 0.3 for spec in PASSES}
        start = time.monotonic()
        _run()
        elapsed = time.monotonic() - start
        # Sequential would take >= 1.2s
        assert elapsed < 0.9, f"passes did not overlap ({elapsed:.2f}s)"

    def test_results_and_sources_keep_pass_order(self, fake):
        # Profile finishes last, content first
        fake.delays = {"profile": 0.3, "news": 0.2, "hiring": 0.1, "content": 0.0}
        brief = _run()

        prompt = fake.synthesis_prompts[0]
        assert "PASS 0: COMPANY PROFILE ---\nprofile research" in prompt
        assert "PASS 1: NEWS ---\nnews research" in prompt
        assert "PASS 2: HIRING ---\nhiring research" in prompt
        assert "PASS 3: CONTENT ---\ncontent research" in prompt

        positions = [brief.index(f"https://example.com/{s.key}") for s in PASSES]
        assert positions == sorted(positions)

    def test_status_updates_report_progress(self, fake):
        messages: list[str] = []
        _run(messages=messages)
        assert sum(m.startswith("✓") for m in messages) == len(PASSES)
        assert any("(4/4)" in m for m in messages)
        assert messages[-1].startswith("🧠")

    def test_profile_uses_fast_model_others_use_research(self, fake):
        brief = _run()
        assert fake.model_for("profile") == ANTHROPIC.fast_model
        for key in ("news", "hiring", "content", "synthesis"):
            assert fake.model_for(key) == ANTHROPIC.research_model
        assert (
            f"*AI model: Anthropic ({ANTHROPIC.research_model}, {ANTHROPIC.fast_model})*"
            in brief
        )


class TestRateLimitFallback:
    def test_falls_back_to_other_provider_when_available(self, fake):
        fake.errors = {("anthropic", "hiring"): LLMRateLimitError("429")}
        brief = _run(fallback=("openai", "server-openai-key"))

        assert ("openai", OPENAI.research_model, "hiring") in fake.calls
        assert "hiring research via openai" in fake.synthesis_prompts[0]
        assert f"· OpenAI fallback ({OPENAI.research_model})" in brief

    def test_fallback_uses_same_tier(self, fake):
        fake.errors = {("anthropic", "profile"): LLMRateLimitError("429")}
        _run(fallback=("openai", "k"))
        assert ("openai", OPENAI.fast_model, "profile") in fake.calls

    def test_synthesis_falls_back_too(self, fake):
        fake.errors = {("anthropic", "synthesis"): LLMRateLimitError("429")}
        brief = _run(fallback=("openai", "k"))
        assert ("openai", OPENAI.research_model, "synthesis") in fake.calls
        assert "OpenAI fallback" in brief

    def test_no_fallback_raises_rate_limit(self, fake):
        """BYOK runs (and server runs without a second key) get no fallback."""
        fake.errors = {("anthropic", "hiring"): LLMRateLimitError("429")}
        with pytest.raises(LLMRateLimitError):
            _run(fallback=None)
        assert not any(p == "openai" for p, _, _ in fake.calls)

    def test_failed_fallback_raises_original_rate_limit(self, fake):
        fake.errors = {
            ("anthropic", "news"): LLMRateLimitError("primary 429"),
            ("openai", "news"): LLMAuthError("bad fallback key"),
        }
        with pytest.raises(LLMRateLimitError, match="primary 429"):
            _run(fallback=("openai", "k"))


class TestFailureHandling:
    def test_one_failed_pass_continues_with_placeholder(self, fake):
        fake.errors = {("anthropic", "content"): LLMTimeoutError("slow")}
        messages: list[str] = []
        brief = _run(messages=messages)

        assert app._PASS_FAILED_TEXT in fake.synthesis_prompts[0]
        assert any(m.startswith("⚠ Content & positioning failed") for m in messages)
        assert "https://example.com/content" not in brief

    def test_two_failed_passes_abort(self, fake):
        fake.errors = {
            ("anthropic", "content"): LLMTimeoutError("slow"),
            ("anthropic", "news"): RuntimeError("boom"),
        }
        with pytest.raises(PipelineError):
            _run()
        assert fake.synthesis_prompts == []

    def test_auth_error_aborts(self, fake):
        fake.errors = {("anthropic", "news"): LLMAuthError("bad key")}
        with pytest.raises(LLMAuthError):
            _run(fallback=("openai", "k"))


class TestFallbackRoute:
    def test_byok_never_falls_back(self, monkeypatch):
        monkeypatch.setenv("OPENAI_API_KEY", "server-key")
        assert app._fallback_route("anthropic", byok="user-key") is None

