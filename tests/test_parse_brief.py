"""
Unit tests for brief parsing (no API key required).

Run: pytest tests/test_parse_brief.py -v
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from app import EXAMPLE_BRIEF, _parse_brief


class TestParseBrief:
    def test_example_brief_has_all_sections(self):
        s = _parse_brief(EXAMPLE_BRIEF)
        for key in ("what", "apart", "doing", "saying", "hiring", "bottom", "sources"):
            assert s[key], f"section {key!r} is empty"
        assert s["what"].startswith("Stripe builds payments")
        assert s["apart"].startswith("Where Adyen and PayPal")
        assert s["date"] == "May 25, 2026"

    def test_example_brief_key_facts(self):
        facts = dict(_parse_brief(EXAMPLE_BRIEF)["facts"])
        assert facts["Founded"] == "2010, by Patrick and John Collison"
        assert facts["CEO"] == "Patrick Collison"
        assert "Adyen" in facts["Main competitors"]
        assert len(facts) == 6

    def test_key_facts_tolerate_bold_labels_and_bullets(self):
        brief = (
            "**Key facts**\n"
            "* **Founded:** 2016\n"
            "• Headquarters: San Francisco\n"
            "- CEO:\n"
            "\n"
            "**What they do** — Makes things."
        )
        s = _parse_brief(brief)
        assert s["facts"] == [("Founded", "2016"), ("Headquarters", "San Francisco")]
        assert s["what"] == "Makes things."

    def test_old_format_brief_still_parses(self):
        """Cached briefs from before the company-profile pass have no overview sections."""
        old = (
            "**What they're doing** — Did a thing.\n\n"
            "**What they're saying** — Said a thing.\n\n"
            "**What hiring signals suggest** — Hired people.\n\n"
            "**Bottom line** — Going places.\n\n"
            "*Generated by Company Intelligence Agent — an agentic AI research tool by Hollis Cooper*\n\n"
            "*Run date: 01 January 2026*"
        )
        s = _parse_brief(old)
        assert s["facts"] == []
        assert s["what"] == ""
        assert s["apart"] == ""
        assert s["doing"] == "Did a thing."
        assert s["bottom"] == "Going places."
        assert s["date"] == "01 January 2026"
